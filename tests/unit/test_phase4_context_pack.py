def half_up(channel: Fraction) -> int:
    adjusted = min(Fraction(255), max(Fraction(0), channel)) + Fraction(1, 2)
    return adjusted.numerator // adjusted.denominator


def exact_hsl_tint(rgb: str, tint: Fraction) -> str:
    """Test-only rational evaluation of §7.7, without intermediate rounding/epsilon."""
    red, green, blue = (Fraction(int(rgb[i : i + 2], 16), 255) for i in (0, 2, 4))
    high, low = max(red, green, blue), min(red, green, blue)
    delta = high - low
    lightness = (high + low) / 2
    if delta == 0:
        hue, saturation = Fraction(0), Fraction(0)
    else:
        saturation = delta / (1 - abs(2 * lightness - 1))
        if high == red:
            hue = ((green - blue) / delta) % 6
        elif high == green:
            hue = (blue - red) / delta + 2
        else:
            hue = (red - green) / delta + 4
        hue /= 6
    lightness = lightness * (1 + tint) if tint < 0 else lightness * (1 - tint) + tint
    chroma = (1 - abs(2 * lightness - 1)) * saturation
    secondary = chroma * (1 - abs((6 * hue) % 2 - 1))
    offset = lightness - chroma / 2
    zero = Fraction(0)
    sectors = [
        (chroma, secondary, zero),
        (secondary, chroma, zero),
        (zero, chroma, secondary),
        (zero, secondary, chroma),
        (secondary, zero, chroma),
        (chroma, zero, secondary),
    ]
    channels = sectors[int(6 * hue) % 6]
    return "".join(f"{half_up((channel + offset) * 255):02X}" for channel in channels)


@pytest.mark.parametrize("name", sorted(MEMBERS))
def test_pack_member_matches_supplied_hash(name: str) -> None:
    manifest = PACK / "SHA256SUMS.txt"
    assert manifest.is_file(), "Corrected pack 2.1.1 must include its supplied hash manifest"
    entries = [line.split("  ", 1) for line in manifest.read_text().splitlines()]
    assert len(entries) == len(MEMBERS)
    assert {filename for _, filename in entries} == MEMBERS
    expected = {filename: digest for digest, filename in entries}
    assert hashlib.sha256((PACK / name).read_bytes()).hexdigest() == expected[name]


