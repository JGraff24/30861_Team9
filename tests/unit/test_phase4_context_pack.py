@pytest.mark.parametrize("base,tint,expected", TINT_CASES)
def test_tint_vector_matches_agreed_constant_and_exact_hsl(base, tint, expected) -> None:
    vector = next(
        item for item in VECTORS["tint"] if item["base_rgb"] == base and item["tint"] == tint
    )
    assert vector["expected_rgb"] == expected
    assert exact_hsl_tint(base, Fraction(str(tint))) == expected


@pytest.mark.parametrize(
    "channel,expected",
    [
        (Fraction(1, 2) - Fraction(1, 10**18), 0),
        (Fraction(1, 2), 1),
        (Fraction(1, 2) + Fraction(1, 10**18), 1),
        (Fraction(5, 2) - Fraction(1, 10**18), 2),
        (Fraction(5, 2), 3),
        (Fraction(5, 2) + Fraction(1, 10**18), 3),
    ],
)
def test_exact_half_up_does_not_promote_genuinely_below_half_values(channel, expected) -> None:
    assert half_up(channel) == expected


def luminance(rgb: str) -> float:
    channels = [int(rgb[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    linear = [
        value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4
        for value in channels
    ]
    return sum(
        weight * value for weight, value in zip((0.2126, 0.7152, 0.0722), linear, strict=True)
    )


@pytest.mark.parametrize("vector", VECTORS["contrast"], ids=lambda item: item["font_rgb"])
def test_contrast_oracles_still_match_unrounded_wcag_thresholds(vector) -> None:
    font, fill = vector["font_rgb"], vector["fill_rgb"]
    first, second = sorted((luminance(font), luminance(fill)))
    ratio = (second + 0.05) / (first + 0.05)
    assert ratio == pytest.approx(vector["ratio"], rel=1e-12)
    assert (ratio >= 4.5) == vector["passes_normal"]
    assert (ratio >= 3.0) == vector["passes_large"]
    nonneutral = any(len({rgb[i : i + 2] for i in (0, 2, 4)}) > 1 for rgb in (font, fill))
    assert nonneutral == vector["has_nonneutral_color"]


